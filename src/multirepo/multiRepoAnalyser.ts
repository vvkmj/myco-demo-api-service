/** Maximum chars of external context to inject into the review prompt. */
const MAX_CROSS_REPO_CONTEXT_CHARS = 30_000;

/** Maximum number of files to scan per external repo for exports. */
const MAX_FILES_PER_REPO = 2_000;

const ALLOWED_EXTENSIONS = new Set([".ts", ".tsx", ".js", ".jsx", ".mjs", ".cjs", ".java", ".go"]);

const IGNORE_DIRS = new Set([
  "node_modules", "dist", "build", ".git", "coverage",
  ".nyc_output", "vendor", "__pycache__", ".next",
]);

// ─────────────────────────────────────────────────────────────────────────────
// Helpers
// ─────────────────────────────────────────────────────────────────────────────

function shouldIgnore(filePath: string): boolean {
  return filePath.split(path.sep).some((seg) => IGNORE_DIRS.has(seg));
}

/**
 * Recursively collect all source files in a directory (up to MAX_FILES_PER_REPO).
 */
function collectSourceFiles(dir: string, limit: number): string[] {
  const files: string[] = [];
  const stack = [dir];

  while (stack.length > 0 && files.length < limit) {
    const current = stack.pop()!;
    let entries: fs.Dirent[];
    try {
      entries = fs.readdirSync(current, { withFileTypes: true });
    } catch {
      continue;
    }

    for (const entry of entries) {
      if (files.length >= limit) break;
      const fullPath = path.join(current, entry.name);

      if (entry.isDirectory()) {
        if (!IGNORE_DIRS.has(entry.name)) stack.push(fullPath);
        continue;
      }

      if (entry.isFile() && ALLOWED_EXTENSIONS.has(path.extname(entry.name))) {
        if (!shouldIgnore(fullPath)) files.push(fullPath);
      }
    }
  }

  return files;
}

/**
 * Extract exported symbols from a TypeScript/JavaScript file.
 */
function extractTsExports(content: string, filePath: string): ExternalExport[] {
  const exports: ExternalExport[] = [];

  // Named exports:  export const/let/var/function/class/type/interface/enum Foo
  const namedExportRe = /^\s*export\s+(?:declare\s+)?(?:const|let|var|function|class|type|interface|enum|abstract\s+class)\s+(\w+)/gm;
  let match: RegExpExecArray | null;
  while ((match = namedExportRe.exec(content)) !== null) {
    exports.push({
      symbolName: match[1],
      filePath,
      exportType: /\btype\b|\binterface\b/.test(match[0]) ? "type" : "named",
      declaration: match[0].trim(),
    });
  }

  // Inline named exports:  export { Foo, Bar, Baz }
  const inlineExportRe = /export\s+\{([^}]+)\}/g;
  while ((match = inlineExportRe.exec(content)) !== null) {
    const names = match[1].split(",").map((s) => {
      const parts = s.trim().split(/\s+as\s+/);
      return parts[parts.length - 1].trim();
    });
    for (const name of names) {
      if (name) {
        exports.push({ symbolName: name, filePath, exportType: "named", declaration: match[0].trim() });
      }
    }
  }

  // Default export:  export default ...
  if (/export\s+default\s+/.test(content)) {
    const defaultMatch = content.match(/export\s+default\s+(?:class|function)?\s*(\w+)?/);
    const name = defaultMatch?.[1] || "default";
    exports.push({ symbolName: name, filePath, exportType: "default", declaration: "export default" });
  }

  // Re-exports:  export { Foo } from './bar'
  const reExportRe = /export\s+\{([^}]+)\}\s+from\s+['"]/g;
  while ((match = reExportRe.exec(content)) !== null) {
    const names = match[1].split(",").map((s) => {
      const parts = s.trim().split(/\s+as\s+/);
      return parts[parts.length - 1].trim();
    });
    for (const name of names) {
      if (name) {
        exports.push({ symbolName: name, filePath, exportType: "re-export", declaration: match[0].trim() });
      }
    }
  }

  // Export * from:  export * from './bar'  — can't extract specific names
  // but we note it for completeness
  const starReExportRe = /export\s+\*\s+from\s+['"]([^'"]+)['"]/g;
  while ((match = starReExportRe.exec(content)) !== null) {
    exports.push({
      symbolName: `*[from ${match[1]}]`,
      filePath,
      exportType: "re-export",
      declaration: match[0].trim(),
    });
  }

  // CommonJS: exports.Foo = ...
  const cjsExportsRe = /\bexports\.(\w+)\s*=/g;
  while ((match = cjsExportsRe.exec(content)) !== null) {
    exports.push({ symbolName: match[1], filePath, exportType: "named", declaration: match[0].trim() });
  }

  // CommonJS: module.exports = { Foo, Bar }
  const cjsModuleExportsRe = /\bmodule\.exports\s*=\s*\{([^}]+)\}/g;
  while ((match = cjsModuleExportsRe.exec(content)) !== null) {
    const names = match[1].split(",").map((s) => s.trim().split(/[:=]/)[0].trim());
    for (const name of names) {
      if (/^[A-Za-z_$][\w$]*$/.test(name)) {
        exports.push({ symbolName: name, filePath, exportType: "named", declaration: `module.exports = { ${name} }` });
      }
    }
  }

  return exports;
}

/**
 * Extract exported symbols from a Go file (capitalized identifiers).
 */
function extractGoExports(content: string, filePath: string): ExternalExport[] {
  const exports: ExternalExport[] = [];
  const goExportRe = /^\s*(?:func\s+(?:\([^)]+\)\s+)?|type\s+|var\s+|const\s+)([A-Z]\w*)/gm;
  let match: RegExpExecArray | null;
  while ((match = goExportRe.exec(content)) !== null) {
    exports.push({
      symbolName: match[1],
      filePath,
      exportType: "named",
      declaration: match[0].trim(),
    });
  }
  return exports;
}

/**
 * Extract exported symbols from a Java file (public classes/interfaces).
 */
function extractJavaExports(content: string, filePath: string): ExternalExport[] {
  const exports: ExternalExport[] = [];

  // Package declaration
  const packageMatch = content.match(/^\s*package\s+([\w.]+)\s*;/m);
  const packageName = packageMatch ? packageMatch[1] : "";

  // Public class/interface/enum/annotation
  const classRe = /^\s*(?:public\s+)?(?:abstract\s+)?(?:class|interface|enum|@interface)\s+(\w+)/gm;
  let match: RegExpExecArray | null;
  while ((match = classRe.exec(content)) !== null) {
    const qualifiedName = packageName ? `${packageName}.${match[1]}` : match[1];
    exports.push({
      symbolName: match[1],
      filePath,
      exportType: "named",
      declaration: `${qualifiedName} (${match[0].trim()})`,
    });
  }

  return exports;
}

/**
 * Build an export index for an external repo: symbol name → ExternalExport[].
 */
function buildExportIndex(repoPath: string): Map<string, ExternalExport[]> {
  const index = new Map<string, ExternalExport[]>();
  const files = collectSourceFiles(repoPath, MAX_FILES_PER_REPO);

  for (const filePath of files) {
    let content: string;
    try {
      content = fs.readFileSync(filePath, "utf-8");
    } catch {
      continue;
    }

    const ext = path.extname(filePath);
    const relPath = path.relative(repoPath, filePath);
    let exports: ExternalExport[];

    if ([".ts", ".tsx", ".js", ".jsx", ".mjs", ".cjs"].includes(ext)) {
      exports = extractTsExports(content, relPath);
    } else if (ext === ".java") {
      exports = extractJavaExports(content, relPath);
    } else if (ext === ".go") {
      exports = extractGoExports(content, relPath);
    } else {
      continue;
    }

    for (const exp of exports) {
      const existing = index.get(exp.symbolName) || [];
      existing.push(exp);
      index.set(exp.symbolName, existing);
    }
  }

  return index;
}

/**
 * Scan the local PR repo for symbols it exports that might be consumed by
 * external repos. Used for reverse-dependency checking.
 * Highly optimized via word tokenization to avoid O(N*M) RegExp compilations.
 * Reuses the pre-built PR export index to avoid redundant disk I/O.
 */
function findConsumedExports(
  prExports: Map<string, ExternalExport[]>,
  externalRepoPath: string
): string[] {
  const consumed: string[] = [];
  if (prExports.size === 0) return consumed;

  const externalFiles = collectSourceFiles(externalRepoPath, MAX_FILES_PER_REPO);
  const exportNames = Array.from(prExports.keys()).filter((s) => s.length >= 2 && !s.startsWith("*"));
  if (exportNames.length === 0) return consumed;

  for (const filePath of externalFiles) {
    let content: string;
    try {
      content = fs.readFileSync(filePath, "utf-8");
    } catch {
      continue;
    }

    const wordMatches = content.match(/\b[A-Za-z_$][\w$]*\b/g);
    if (!wordMatches) continue;
    const wordSet = new Set(wordMatches);

    for (const symbolName of exportNames) {
      if (wordSet.has(symbolName) && !consumed.includes(symbolName)) {
        consumed.push(symbolName);
      }
    }
  }

  return consumed;
}

interface RemovedExportInfo {
  symbol: string;
  file: string;
  line: number | null;
}

/**
 * Scan diff patches for exported symbols that were removed or deleted in this PR.
 * Used to detect downstream breakage in external consumer repositories.
 */
function findRemovedExportsFromDiff(diff: DiffContext): RemovedExportInfo[] {
  const removed: RemovedExportInfo[] = [];

  for (const file of diff.changedFiles) {
    if (!file.patch) continue;

    const lines = file.patch.split("\n");
    let currentOldLine = 0;

    for (const line of lines) {
      if (line.startsWith("@@")) {
        const match = line.match(/@@\s+-(\d+)/);
        if (match) currentOldLine = parseInt(match[1], 10) - 1;
        continue;
      }

      if (line.startsWith("-")) {
        currentOldLine++;
        const deletedCode = line.slice(1).trim();

        // 1. TS/JS named exports: export (const|function|class|type|interface|enum) Foo
        const tsMatch = deletedCode.match(
          /^export\s+(?:declare\s+)?(?:const|let|var|function|class|type|interface|enum|abstract\s+class)\s+(\w+)/
        );
        if (tsMatch) {
          removed.push({ symbol: tsMatch[1], file: file.filename, line: currentOldLine });
          continue;
        }

        // 2. TS/JS inline exports: export { Foo, Bar }
        const inlineMatch = deletedCode.match(/^export\s+\{([^}]+)\}/);
        if (inlineMatch) {
          const symbols = inlineMatch[1].split(",").map((s) => {
            const parts = s.trim().split(/\s+as\s+/);
            return parts[parts.length - 1].trim();
          });
          for (const sym of symbols) {
            if (sym && /^[A-Za-z_$][\w$]*$/.test(sym)) {
              removed.push({ symbol: sym, file: file.filename, line: currentOldLine });
            }
          }
          continue;
        }

        // 3. CommonJS: exports.Foo = ...
        const cjsMatch = deletedCode.match(/\bexports\.(\w+)\s*=/);
        if (cjsMatch) {
          removed.push({ symbol: cjsMatch[1], file: file.filename, line: currentOldLine });
          continue;
        }

        // 4. Go: func Foo or type Foo
        const goMatch = deletedCode.match(/^(?:func\s+(?:\([^)]+\)\s+)?|type\s+|var\s+|const\s+)([A-Z]\w*)/);
        if (goMatch) {
          removed.push({ symbol: goMatch[1], file: file.filename, line: currentOldLine });
          continue;
        }

        // 5. Java: public class Foo
        const javaMatch = deletedCode.match(/^public\s+(?:abstract\s+)?(?:class|interface|enum)\s+(\w+)/);
        if (javaMatch) {
          removed.push({ symbol: javaMatch[1], file: file.filename, line: currentOldLine });
          continue;
        }
      } else if (!line.startsWith("+")) {
        currentOldLine++;
      }
    }
  }

  return removed;
}

function escapeRegExp(value: string): string {
  return value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

/**
 * Parse function parameters and calculate the minimum required arguments
 * (count of required parameters before the first optional/default/rest param).
 */
export function parseFunctionParams(decl: string): { params: ParsedParam[]; minArgs: number } {
  const openParen = decl.indexOf("(");
  if (openParen === -1) return { params: [], minArgs: 0 };

  let depth = 0;
  let endParen = -1;
  for (let i = openParen; i < decl.length; i++) {
    const ch = decl[i];
    if (ch === "(") depth++;
    else if (ch === ")") {
      depth--;
      if (depth === 0) {
        endParen = i;
        break;
      }
    }
  }

  if (endParen === -1) return { params: [], minArgs: 0 };
  const rawParams = decl.slice(openParen + 1, endParen).trim();
  if (!rawParams) return { params: [], minArgs: 0 };

  const paramStrings: string[] = [];
  let current = "";
  let pDepth = 0;
  for (let i = 0; i < rawParams.length; i++) {
    const ch = rawParams[i];
    if (ch === "{" || ch === "[" || ch === "(" || ch === "<") pDepth++;
    else if (ch === "}" || ch === "]" || ch === ")" || ch === ">") pDepth--;
    else if (ch === "," && pDepth === 0) {
      if (current.trim()) paramStrings.push(current.trim());
      current = "";
      continue;
    }
    current += ch;
  }
  if (current.trim()) paramStrings.push(current.trim());

  const params: ParsedParam[] = [];
  let minArgs = 0;
  let seenOptional = false;

  for (const p of paramStrings) {
    const hasDefault = p.includes("=");
    const isRest = p.trim().startsWith("...");
    const isMarkedOptional = /^\w+\?\s*:/.test(p.trim()) || hasDefault || isRest;

    const nameMatch = p.trim().match(/^(\.{3})?([A-Za-z_$][\w$]*)/);
    const name = nameMatch ? nameMatch[2] : p.trim();

    if (!isMarkedOptional && !seenOptional) {
      minArgs++;
    } else {
      seenOptional = true;
    }

    params.push({
      name,
      isOptional: isMarkedOptional,
      hasDefault,
    });
  }

  return { params, minArgs };
}

/**
 * Extract arguments passed to a function call in a single line or code snippet.
 */
export function extractCallArguments(lineOrSnippet: string, symbolName: string): string[] {
  const symIdx = lineOrSnippet.indexOf(symbolName);
  if (symIdx === -1) return [];

  const openParen = lineOrSnippet.indexOf("(", symIdx + symbolName.length);
  if (openParen === -1) return [];

  let depth = 0;
  let endParen = -1;
  for (let i = openParen; i < lineOrSnippet.length; i++) {
    const ch = lineOrSnippet[i];
    if (ch === "(") depth++;
    else if (ch === ")") {
      depth--;
      if (depth === 0) {
        endParen = i;
        break;
      }
    }
  }

  if (endParen === -1) return [];
  const argsRaw = lineOrSnippet.slice(openParen + 1, endParen).trim();
  if (!argsRaw) return [];

  const args: string[] = [];
  let current = "";
  let pDepth = 0;
  for (let i = 0; i < argsRaw.length; i++) {
    const ch = argsRaw[i];
    if (ch === "{" || ch === "[" || ch === "(") pDepth++;
    else if (ch === "}" || ch === "]" || ch === ")") pDepth--;
    else if (ch === "," && pDepth === 0) {
      if (current.trim()) args.push(current.trim());
      current = "";
      continue;
    }
    current += ch;
  }
  if (current.trim()) args.push(current.trim());
  return args;
}

/**
 * Parse properties out of an interface or type declaration body.
 */
export function parseInterfaceProperties(decl: string): Set<string> {
  const props = new Set<string>();
  const openBrace = decl.indexOf("{");
  const closeBrace = decl.lastIndexOf("}");
  if (openBrace === -1 || closeBrace === -1 || closeBrace <= openBrace) return props;

  const body = decl.slice(openBrace + 1, closeBrace);
  const propRe = /(?:^|[;,{\n])\s*(?:readonly\s+)?([A-Za-z_$][\w$]*)\s*\??\s*[:=]/g;
  let m: RegExpExecArray | null;
  while ((m = propRe.exec(body)) !== null) {
    if (m[1] && !["export", "function", "class", "interface", "type", "return"].includes(m[1])) {
      props.add(m[1]);
    }
  }
  return props;
}

/**
 * Scan an external repository for concrete call-sites/usages of an exported symbol.
 */
export function findConsumerCallSites(
  externalRepoPath: string,
  repoSlug: string,
  symbolName: string
): ConsumerCallSite[] {
  const callSites: ConsumerCallSite[] = [];
  const files = collectSourceFiles(externalRepoPath, MAX_FILES_PER_REPO);
  const regex = new RegExp(`\\b${escapeRegExp(symbolName)}\\b`);

  for (const filePath of files) {
    let content: string;
    try {
      content = fs.readFileSync(filePath, "utf-8");
    } catch {
      continue;
    }

    if (!regex.test(content)) continue;

    const lines = content.split("\n");
    const relFile = path.relative(externalRepoPath, filePath);

    for (let i = 0; i < lines.length; i++) {
      const line = lines[i];
      if (regex.test(line)) {
        const trimmed = line.trim();
        // Skip comment lines
        if (trimmed.startsWith("//") || trimmed.startsWith("/*") || trimmed.startsWith("*")) {
          continue;
        }

        // Skip purely import/export statement lines that do not execute a call
        if (/^\s*(?:import|export)\b/.test(line) && !line.includes("(")) {
          continue;
        }

        const argsPassed = extractCallArguments(line, symbolName);
        const argsCount = argsPassed.length;

        const contextLines: string[] = [];
        if (i > 0) contextLines.push(`${i}: ${lines[i - 1]}`);
        contextLines.push(`${i + 1}: ${line}`);
        if (i < lines.length - 1) contextLines.push(`${i + 2}: ${lines[i + 1]}`);

        callSites.push({
          repoSlug,
          filePath: relFile,
          lineNumber: i + 1,
          lineText: line.trim(),
          argsPassed,
          argsCount,
          surroundingContext: contextLines.join("\n"),
        });

        if (callSites.length >= 10) break;
      }
    }
  }

  return callSites;
}

/**
 * Scan diff patches for exported symbols that were modified (not deleted) in this PR.
 * Captures signature changes, added required parameters, and removed interface properties.
 */
function findModifiedExportsFromDiff(
  diff: DiffContext,
  prExportIndex: Map<string, ExternalExport[]>,
  repoPath: string
): ModifiedExportInfo[] {
  const modified: ModifiedExportInfo[] = [];

  for (const file of diff.changedFiles) {
    if (!file.patch) continue;

    const lines = file.patch.split("\n");
    let currentNewLine = 0;

    const deletedDecls = new Map<string, { decl: string; line: number }>();
    const addedDecls = new Map<string, { decl: string; line: number }>();

    for (const line of lines) {
      if (line.startsWith("@@")) {
        const match = line.match(/@@\s+-\d+(?:,\d+)?\s+\+(\d+)/);
        if (match) currentNewLine = parseInt(match[1], 10) - 1;
        continue;
      }

      if (line.startsWith("-")) {
        const text = line.slice(1).trim();
        const symMatch = text.match(
          /^export\s+(?:declare\s+)?(?:const|let|var|function|class|type|interface|enum|abstract\s+class)\s+(\w+)/
        );
        if (symMatch) {
          deletedDecls.set(symMatch[1], { decl: text, line: currentNewLine });
        }
      } else if (line.startsWith("+")) {
        currentNewLine++;
        const text = line.slice(1).trim();
        const symMatch = text.match(
          /^export\s+(?:declare\s+)?(?:const|let|var|function|class|type|interface|enum|abstract\s+class)\s+(\w+)/
        );
        if (symMatch) {
          addedDecls.set(symMatch[1], { decl: text, line: currentNewLine });
        }
      } else {
        currentNewLine++;
      }
    }

    // Compare symbols that were modified in this file
    for (const [sym, oldInfo] of deletedDecls.entries()) {
      if (!prExportIndex.has(sym)) continue; // completely removed — handled separately

      const currentExports = prExportIndex.get(sym) || [];
      const matchingCurrent = currentExports.find((e) => e.filePath === file.filename) || currentExports[0];
      const newDecl = addedDecls.get(sym)?.decl || matchingCurrent?.declaration || "";
      const lineNum = addedDecls.get(sym)?.line || oldInfo.line;

      const isFunc = /\bfunction\b|\b=>\b/.test(oldInfo.decl) || /\bfunction\b|\b=>\b/.test(newDecl);
      const isInterface = /\binterface\b|\btype\b/.test(oldInfo.decl) || /\binterface\b|\btype\b/.test(newDecl);

      let oldMinArgs: number | undefined;
      let newMinArgs: number | undefined;
      let removedProperties: string[] | undefined;

      if (isFunc) {
        const oldParsed = parseFunctionParams(oldInfo.decl);
        const newParsed = parseFunctionParams(newDecl);
        oldMinArgs = oldParsed.minArgs;
        newMinArgs = newParsed.minArgs;
      }

      if (isInterface) {
        const oldProps = parseInterfaceProperties(oldInfo.decl);
        const newProps = parseInterfaceProperties(newDecl);
        const rem: string[] = [];
        for (const p of oldProps) {
          if (!newProps.has(p)) rem.push(p);
        }
        if (rem.length > 0) removedProperties = rem;
      }

      modified.push({
        symbol: sym,
        file: file.filename,
        line: lineNum,
        kind: isFunc ? "function" : isInterface ? "interface" : "variable",
        oldDeclaration: oldInfo.decl,
        newDeclaration: newDecl,
        oldMinArgs,
        newMinArgs,
        removedProperties,
      });
    }

    // Also detect property removals inside interfaces/types when the declaration line itself wasn't changed
    for (const [sym, exps] of prExportIndex.entries()) {
      if (deletedDecls.has(sym)) continue;
      const exp = exps.find((e) => e.filePath === file.filename);
      if (!exp || (exp.exportType !== "type" && !exp.declaration.includes("interface"))) continue;

      const removedPropsInFile: string[] = [];
      for (const line of lines) {
        if (line.startsWith("-") && !line.startsWith("---")) {
          const propMatch = line.slice(1).match(/^\s*(?:readonly\s+)?([A-Za-z_$][\w$]*)\s*\??\s*[:=]/);
          if (propMatch && !["export", "function", "class", "interface", "type"].includes(propMatch[1])) {
            removedPropsInFile.push(propMatch[1]);
          }
        }
      }

      if (removedPropsInFile.length > 0) {
        modified.push({
          symbol: sym,
          file: file.filename,
          line: 1,
          kind: "interface",
          oldDeclaration: exp.declaration,
          newDeclaration: exp.declaration,
          removedProperties: removedPropsInFile,
        });
      }
    }
  }

  return modified;
}

/**
 * Find the 1-indexed line number in a file where an imported symbol appears.
 */
function findImportLineNumber(fullFilePath: string, symbol: string): number | null {
  try {
    if (!fs.existsSync(fullFilePath)) return null;
    const content = fs.readFileSync(fullFilePath, "utf-8");
    const lines = content.split("\n");
    for (let i = 0; i < lines.length; i++) {
      if (new RegExp(`\\b${escapeRegExp(symbol)}\\b`).test(lines[i])) {
        return i + 1;
      }
    }
  } catch {}
  return null;
}

