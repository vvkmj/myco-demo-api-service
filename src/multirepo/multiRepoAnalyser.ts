/**
 * An exported symbol discovered in an external repository.
 */
export interface ExternalExport {
  /** The symbol name (e.g. "UserType", "createApiClient"). */
  symbolName: string;
  /** The file path (relative to repo root) where it's exported. */
  filePath: string;
  /** The export type: named, default, re-export, type. */
  exportType: "named" | "default" | "re-export" | "type";
  /** The full line of the export declaration. */
  declaration: string;
}

/**
 * A concrete call-site or usage of an export in a downstream consumer repository.
 */
export interface ConsumerCallSite {
  repoSlug: string;
  filePath: string;
  lineNumber: number;
  lineText: string;
  argsPassed: string[];
  argsCount: number;
  surroundingContext?: string;
}

/**
 * Information about an export that was modified (not removed) in the PR diff.
 */
export interface ModifiedExportInfo {
  symbol: string;
  file: string;
  line: number | null;
  kind: "function" | "interface" | "type" | "class" | "variable" | "other";
  oldDeclaration: string;
  newDeclaration: string;
  oldMinArgs?: number;
  newMinArgs?: number;
  removedProperties?: string[];
  addedRequiredProperties?: string[];
}

/**
 * Parsed function parameter metadata.
 */
export interface ParsedParam {
  name: string;
  isOptional: boolean;
  hasDefault: boolean;
}

/**
 * Result of analyzing a single cross-repo dependency.
 */
export interface CrossRepoAnalysisResult {
  /** The external repo slug. */
  repoSlug: string;
  /** Whether the analysis succeeded. */
  success: boolean;
  /** Symbols that the PR imports and the external repo exports (verified OK). */
  verifiedImports: string[];
  /** Symbols that the PR imports but the external repo does NOT export (broken). */
  brokenImports: string[];
  /** Symbols that the PR exports and the external repo imports (consumers at risk). */
  consumedExports: string[];
  /** Deterministic findings generated by the analyser. */
  findings: FindingCard[];
  /** Context snippet for the LLM reviewer (external repo's relevant exports). */
  contextSnippet: string;
  /** Error message if analysis failed. */
  error?: string;
}

/**
 * Full result of multi-repo analysis across all external dependencies.
 */
export interface MultiRepoAnalysis {
  /** Per-repo analysis results. */
  results: CrossRepoAnalysisResult[];
  /** All deterministic cross-repo findings (broken imports, missing exports). */
  findings: FindingCard[];
  /** Aggregated context for the LLM prompt. */
  contextForReview: string;
  /** Map of repo slug → local path for read_file tool access. */
  repoPathMap: Map<string, string>;
}

