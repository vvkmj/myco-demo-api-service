/**
 * Analyze cross-repo dependencies by checking import/export compatibility in both directions:
 * 1. PR imports from external repo (verified against external repo's actual exports)
 * 2. External repo consumes PR repo exports (breaking change detection if PR removes exports)
 *
 * @param clonedRepos  Successfully cloned external repos
 * @param prRepoPath   Path to the locally cloned PR repo
 * @param diff         Optional PR diff context for detecting deleted exports
 * @returns            Analysis results with deterministic findings and context
 */
export function analyzeMultiRepoDependencies(
  clonedRepos: ClonedExternalRepo[],
  prRepoPath: string,
  diff?: DiffContext
): MultiRepoAnalysis {
  const results: CrossRepoAnalysisResult[] = [];
  const allFindings: FindingCard[] = [];
  const contextParts: string[] = [];
  const repoPathMap = new Map<string, string>();
  let totalContextChars = 0;

  console.log("\n🔍  Analyzing cross-repository dependencies...");

  // Cache PR export index once for performance across all external repo checks
  const prExportIndex = buildExportIndex(prRepoPath);
  const removedExports = diff ? findRemovedExportsFromDiff(diff) : [];

  for (const cloned of clonedRepos) {
    if (!cloned.success) {
      results.push({
        repoSlug: cloned.repoSlug,
        success: false,
        verifiedImports: [],
        brokenImports: [],
        consumedExports: [],
        findings: [],
        contextSnippet: "",
        error: cloned.error || "Clone failed",
      });
      continue;
    }

    console.log(`  🔬  Analyzing ${cloned.repoSlug}...`);
    repoPathMap.set(cloned.repoSlug, cloned.localPath);
    const dep = cloned.dependency;
    for (const spec of dep.importSpecifiers) {
      repoPathMap.set(spec, cloned.localPath);
    }

    try {
      // 1. Build export index for the external repo
      const exportIndex = buildExportIndex(cloned.localPath);
      console.log(`     📊  Found ${exportIndex.size} exported symbol(s).`);

      // 2. Verify imports from external repo
      const verified: string[] = [];
      const broken: string[] = [];

      for (const symbol of dep.importedSymbols) {
        // Skip wildcard or default-like symbols
        if (symbol === "*" || symbol === "default") {
          verified.push(symbol);
          continue;
        }

        const exports = exportIndex.get(symbol);
        if (exports && exports.length > 0) {
          verified.push(symbol);
        } else {
          broken.push(symbol);
        }
      }

      // 3. Generate deterministic findings for broken imports with exact lines
      const repoFindings: FindingCard[] = [];
      for (const brokenSymbol of broken) {
        const refRel = dep.referencingFiles[0] || "unknown";
        const fullRefPath = path.resolve(prRepoPath, refRel);
        const importLine = findImportLineNumber(fullRefPath, brokenSymbol);
        const locationLabel = importLine ? `${refRel} · line ${importLine}` : refRel;

        const finding: FindingCard = {
          id: `P1-XREPO-${allFindings.length + repoFindings.length + 1}`,
          severity: "P1",
          title: `Cross-repo import "${brokenSymbol}" not found in ${dep.repoSlug}`,
          file: locationLabel,
          filePath: refRel,
          line: importLine,
          rootCause:
            `The PR imports symbol "${brokenSymbol}" from external repo ${dep.repoSlug} ` +
            `(via ${dep.importSpecifiers[0]}), but this symbol is not exported by that repository ` +
            `on branch "${cloned.branch}". This will cause a build/compilation failure.`,
          impact:
            `Build will fail with "cannot find module" or "not exported" error. ` +
            `Any deployment depending on this import path will be broken.`,
          fix:
            `Verify that "${brokenSymbol}" is exported from ${dep.repoSlug}. If it was recently ` +
            `renamed or removed, update the import to use the correct symbol name. If it's a new ` +
            `addition, ensure the external repo has been published with this export.`,
        };
        repoFindings.push(finding);
      }

      // 4. Check reverse dependencies (does the external repo import from us?)
      let consumed: string[] = [];
      try {
        consumed = findConsumedExports(prExportIndex, cloned.localPath);
        if (consumed.length > 0) {
          console.log(`     ↩️   ${dep.repoSlug} consumes ${consumed.length} export(s) from this repo.`);
        }
      } catch {
        // Non-critical — reverse dependency check is best-effort
      }

      // 5. Detect breaking changes in exports consumed by external repo ("and vice versa")
      if (removedExports.length > 0) {
        const externalFiles = collectSourceFiles(cloned.localPath, MAX_FILES_PER_REPO);
        for (const rem of removedExports) {
          if (!prExportIndex.has(rem.symbol)) {
            // Check if any external file uses this removed symbol
            let isConsumed = consumed.includes(rem.symbol);
            if (!isConsumed) {
              for (const extFile of externalFiles) {
                try {
                  const content = fs.readFileSync(extFile, "utf-8");
                  if (new RegExp(`\\b${escapeRegExp(rem.symbol)}\\b`).test(content)) {
                    isConsumed = true;
                    if (!consumed.includes(rem.symbol)) consumed.push(rem.symbol);
                    break;
                  }
                } catch {}
              }
            }

            if (isConsumed) {
              const locationLabel = rem.line ? `${rem.file} · line ${rem.line}` : rem.file;
              const finding: FindingCard = {
                id: `P1-XREPO-${allFindings.length + repoFindings.length + 1}`,
                severity: "P1",
                title: `Breaking change: export "${rem.symbol}" consumed by ${dep.repoSlug} was removed`,
                file: locationLabel,
                filePath: rem.file,
                line: rem.line,
                rootCause:
                  `The PR removes or modifies exported symbol "${rem.symbol}" in ${rem.file}, ` +
                  `which is actively consumed by external repository ${dep.repoSlug}. ` +
                  `This is a downstream breaking change that will break builds or runtime flows in that repository.`,
                impact:
                  `External repository ${dep.repoSlug} depends on "${rem.symbol}". ` +
                  `Merging this change without updating or coordinating with ${dep.repoSlug} will break downstream builds.`,
                fix:
                  `Retain backward compatibility for "${rem.symbol}" in ${rem.file} (deprecate rather than delete), ` +
                  `provide a backward-compatible alias, or coordinate a synchronized release with ${dep.repoSlug}.`,
              };
              repoFindings.push(finding);
              console.log(`     ⚠️   Downstream breaking change detected: "${rem.symbol}" consumed by ${dep.repoSlug}`);
            }
          }
        }
      }

      // 6. Build context snippet for the reviewer
      let contextSnippet = "";
      if (totalContextChars < MAX_CROSS_REPO_CONTEXT_CHARS) {
        const snippetParts: string[] = [
          `\n### External Repo: ${dep.repoSlug} (branch: ${cloned.branch})`,
          `**Imported symbols:** ${dep.importedSymbols.join(", ") || "none extracted"}`,
          `**Verified exports:** ${verified.join(", ") || "none"}`,
        ];

        if (broken.length > 0) {
          snippetParts.push(`**⚠️ MISSING exports:** ${broken.join(", ")}`);
        }

        if (consumed.length > 0) {
          snippetParts.push(`**Consumed from PR repo:** ${consumed.join(", ")}`);
        }

        // Include the relevant export declarations for context
        const relevantExports: string[] = [];
        for (const symbol of verified) {
          const exports = exportIndex.get(symbol);
          if (exports) {
            for (const exp of exports.slice(0, 2)) {
              relevantExports.push(`  ${exp.symbolName} (${exp.filePath}): ${exp.declaration}`);
            }
          }
        }

        if (relevantExports.length > 0) {
          snippetParts.push(`\n**Relevant export declarations:**`);
          snippetParts.push(...relevantExports);
        }

        contextSnippet = snippetParts.join("\n");
        totalContextChars += contextSnippet.length;
      }

      // Log results
      if (verified.length > 0) {
        console.log(`     ✅  ${verified.length} import(s) verified OK.`);
      }
      if (broken.length > 0) {
        console.log(`     ❌  ${broken.length} import(s) NOT found — findings generated.`);
      }

      allFindings.push(...repoFindings);
      contextParts.push(contextSnippet);

      results.push({
        repoSlug: cloned.repoSlug,
        success: true,
        verifiedImports: verified,
        brokenImports: broken,
        consumedExports: consumed,
        findings: repoFindings,
        contextSnippet,
      });
    } catch (err: any) {
      console.warn(`  ⚠️   Analysis failed for ${cloned.repoSlug}: ${err.message}`);
      results.push({
        repoSlug: cloned.repoSlug,
        success: false,
        verifiedImports: [],
        brokenImports: [],
        consumedExports: [],
        findings: [],
        contextSnippet: "",
        error: err.message,
      });
    }
  }

  const contextForReview = contextParts.filter(Boolean).join("\n\n");

  if (allFindings.length > 0) {
    console.log(`\n🚫  Cross-repo analysis found ${allFindings.length} issue(s).`);
  } else {
    console.log("\n✅  Cross-repo analysis complete — no issues found.");
  }

  return {
    results,
    findings: allFindings,
    contextForReview,
    repoPathMap,
  };
}
